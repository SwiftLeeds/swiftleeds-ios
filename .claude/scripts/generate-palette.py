#!/usr/bin/env python3
"""Generate the tonal colour ramps of every Hue, and the color families built from them.

Each hue is a ramp from t5 to t95 in OKLCH, converted to Display P3. Two outputs, both under
Packages/DesignSystem/UIDesign/Sources/UIDesign:
- Tokens/Colors/Hue/Hue+Tones.swift, the ramps as Swift Color.Resolved literals.
- Resources/Colors.xcassets, one color set per family and role (light, dark and increased contrast).
  The whole catalog is deleted and rewritten on each run.

Run it from the repo root: python3 .claude/scripts/generate-palette.py
Pass --output-root <directory> to write both outputs into that directory instead.
Failures are appended to generate-palette.log beside the script. Standard library only.
"""

import argparse
import colorsys
import itertools
import json
import math
import re
import shutil
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

LOG_PATH = Path(__file__).resolve().parent / "generate-palette.log"
DEFAULT_ROOT = Path(__file__).resolve().parents[2]
TONES = list(range(5, 100, 5))
TOLERANCE = 1e-5
DECIMALS = 4
HEADER = "// Generated by .claude/scripts/generate-palette.py. Do not edit; run the script."


def log_failure(message):
    """Append a failure to the log. Failures only, never progress."""
    stamp = datetime.now().isoformat(timespec="seconds")
    with open(LOG_PATH, "a", encoding="utf-8") as handle:
        handle.write(f"{stamp} {message}\n")


def fail(message):
    """Log the failure, print it and exit with status 1."""
    log_failure(message)
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def mat_mul(a, b):
    """Returns the product of two 3 by 3 matrices."""
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def mat_vec(m, v):
    """Returns a 3 by 3 matrix times a 3-vector."""
    return [sum(m[i][k] * v[k] for k in range(3)) for i in range(3)]


def mat_inv(m):
    """Returns the inverse of a 3 by 3 matrix."""
    (a, b, c), (d, e, f), (g, h, i) = m
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return [
        [(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
        [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
        [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det],
    ]


SRGB_TO_XYZ = [
    [0.4123907993, 0.3575843394, 0.1804807884],
    [0.2126390059, 0.7151686788, 0.0721923154],
    [0.0193308187, 0.1191947798, 0.9505321522],
]
P3_TO_XYZ = [
    [0.4865709486, 0.2656676932, 0.1982172852],
    [0.2289745641, 0.6917385218, 0.0792869141],
    [0.0000000000, 0.0451133819, 1.0439443689],
]
XYZ_TO_P3 = mat_inv(P3_TO_XYZ)
SRGB_TO_P3 = mat_mul(XYZ_TO_P3, SRGB_TO_XYZ)
P3_TO_SRGB = mat_inv(SRGB_TO_P3)


def decode(c):
    """Gamma-encoded to linear (the sRGB transfer curve, shared by Display P3)."""
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def encode(c):
    """Linear to gamma-encoded, clamped to 0...1."""
    c = min(max(c, 0.0), 1.0)
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def cbrt(x):
    """Returns the cube root, keeping the sign of a negative input."""
    return math.copysign(abs(x) ** (1 / 3), x)


# The OKLab matrices below are Björn Ottosson's, from https://bottosson.github.io/posts/oklab/
def linear_srgb_to_oklab(rgb):
    """Linear sRGB to OKLab (L, a, b)."""
    r, g, b = rgb
    l = cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
    m = cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
    s = cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
    return (
        0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
        1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
        0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s,
    )


def oklab_to_linear_srgb(lab):
    """OKLab (L, a, b) to linear sRGB."""
    big_l, a, b = lab
    l = (big_l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (big_l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (big_l - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
    )


def oklch_to_linear_p3(lightness, chroma, hue_degrees):
    """OKLCH to linear Display P3 components."""
    angle = math.radians(hue_degrees)
    lab = (lightness, chroma * math.cos(angle), chroma * math.sin(angle))
    return mat_vec(SRGB_TO_P3, oklab_to_linear_srgb(lab))


def oklch_to_p3(lightness, chroma, hue_degrees):
    """Gamma-encoded Display P3 components, unrounded."""
    return [encode(c) for c in oklch_to_linear_p3(lightness, chroma, hue_degrees)]


def in_p3_gamut(lightness, chroma, hue_degrees):
    """Returns whether the OKLCH color fits inside Display P3."""
    return all(0.0 <= c <= 1.0 for c in oklch_to_linear_p3(lightness, chroma, hue_degrees))


def max_p3_chroma(lightness, hue_degrees, ceiling):
    """Largest chroma up to the ceiling that stays inside Display P3, by bisection."""
    if in_p3_gamut(lightness, ceiling, hue_degrees):
        return ceiling
    low, high = 0.0, ceiling
    while high - low > TOLERANCE:
        mid = (low + high) / 2
        if in_p3_gamut(lightness, mid, hue_degrees):
            low = mid
        else:
            high = mid
    return low


def srgb_to_oklch(red, green, blue):
    """Gamma-encoded sRGB (0...1) to (L, C, hue in degrees)."""
    lab = linear_srgb_to_oklab([decode(red), decode(green), decode(blue)])
    chroma = math.hypot(lab[1], lab[2])
    return lab[0], chroma, math.degrees(math.atan2(lab[2], lab[1])) % 360


def hex_to_oklch(hex_string):
    """A hex color such as FF3B30 to (L, C, hue in degrees)."""
    text = hex_string.lstrip("#")
    red, green, blue = (int(text[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return srgb_to_oklch(red, green, blue)


def hsb_to_oklch(hue, saturation, brightness):
    """Hue, saturation and brightness (each 0...1) to (L, C, hue in degrees)."""
    return srgb_to_oklch(*colorsys.hsv_to_rgb(hue, saturation, brightness))


CAP = 0.20  # Default chroma cap. Change a row below to retune one hue.


TURN_START = 75  # A turning hue keeps its angle from this tone up.
TURN_END = 45  # A turning hue reaches turn_to at this tone and keeps it below.

TAPER_START = 75  # Chroma is full up to this tone.
TAPER_END = 95
TAPER_FLOOR = 0.35  # Fraction of the cap left at TAPER_END.


@dataclass(frozen=True)
class HueRow:
    name: str
    angle: float
    cap: float
    # The angle at TURN_END and below, for a hue that turns as it darkens. None keeps one angle.
    turn_to: float | None = None
    # The tone from which chroma tapers toward TAPER_FLOOR at TAPER_END.
    taper_start: int = TAPER_START

    def angle_at(self, tone):
        """Returns the hue angle at a tone: the row's angle, or a straight turn between TURN_START and TURN_END."""
        if self.turn_to is None or tone >= TURN_START:
            return self.angle
        if tone <= TURN_END:
            return self.turn_to
        return self.turn_to + (self.angle - self.turn_to) * (tone - TURN_END) / (TURN_START - TURN_END)


def build_hue_table():
    """One row per hue. The source colour of each angle is written out here."""
    red = hex_to_oklch("FF3B30")[2]  # Apple system red, light mode
    green = hex_to_oklch("34C759")[2]  # Apple system green
    yellow = hex_to_oklch("FFCC00")[2]  # Apple system yellow
    # The hue of blue, teal, violet and raspberry (0.60, 0.47, 0.76, 0.92) is the session-kind hue
    # from the design gallery. Saturation and brightness were chosen here, and only the resulting
    # OKLCH hue angle is used.
    blue = hsb_to_oklch(0.60, 0.75, 0.85)[2]
    teal = hsb_to_oklch(0.47, 0.75, 0.70)[2]
    violet = hsb_to_oklch(0.76, 0.60, 0.80)[2]
    raspberry = hsb_to_oklch(0.92, 0.70, 0.80)[2]
    return [
        HueRow("red", red, CAP),
        HueRow("green", green, CAP),
        # Turns toward amber as it darkens, so its text tones read as amber, not olive. Yellow's chroma
        # peaks at t85 to t90, so its taper starts there.
        HueRow("yellow", yellow, CAP, turn_to=55.0, taper_start=90),
        HueRow("blue", blue, CAP),
        HueRow("teal", teal, CAP),
        HueRow("violet", violet, CAP),
        HueRow("raspberry", raspberry, CAP),
        HueRow("neutral", 0.0, 0.0),
        # Between raspberry (355) and violet (307) at a third of their chroma, so it reads as neither.
        HueRow("mauve", 340.0, 0.07),
    ]


HUES = build_hue_table()


def chroma_factor(tone, taper_start):
    """1.0 up to taper_start, then a straight line down to TAPER_FLOOR at TAPER_END."""
    if tone <= taper_start:
        return 1.0
    return 1.0 - (1.0 - TAPER_FLOOR) * (tone - taper_start) / (TAPER_END - taper_start)


def ramp(row):
    """List of (tone, chroma, [p3 r, g, b rounded to 4 decimals]) from t5 to t95 for a HueRow."""
    if row.taper_start >= TAPER_END:
        fail(f"{row.name} starts its taper at t{row.taper_start}, which is not below t{TAPER_END}")
    result = []
    for tone in TONES:
        lightness = tone / 100
        angle = row.angle_at(tone)
        ceiling = row.cap * chroma_factor(tone, row.taper_start)
        chroma = max_p3_chroma(lightness, angle, ceiling) if ceiling > 0 else 0.0
        rgb = oklch_to_p3(lightness, chroma, angle)
        rounded = [min(max(round(c, DECIMALS), 0.0), 1.0) + 0.0 for c in rgb]
        result.append((tone, chroma, rounded))
    return result


def literal(rgb):
    """Returns the Swift Color.Resolved literal for Display P3 components."""
    return "Color.Resolved(colorSpace: .displayP3, red: {:.4f}, green: {:.4f}, blue: {:.4f})".format(*rgb)


def hue_file(ramps):
    """ramps: dict hue name -> ramp()."""
    lines = [
        HEADER,
        "// Each hue's function has one case per tone, so it disables cyclomatic_complexity on its line.",
        "// Permanent while this file is generated.",
        "",
        "import SwiftUI",
        "",
        "// swiftlint:disable no_magic_numbers - raw token values, generated",
        "extension Hue {",
    ]
    lines += [
        "    /// Returns the raw color of this hue at a tone.",
        "    ///",
        "    /// ```swift",
        "    /// let fill = Color(Hue.blue.tone(.t50))",
        "    /// ```",
        "    ///",
        "    /// - Parameter tone: The tone to read, from darkest to lightest.",
        "    /// - Returns: The color, in the Display P3 color space.",
        "    package func tone(_ tone: Tone) -> Color.Resolved {",
        "        switch self {",
    ]
    lines += [f"        case .{row.name}: Self.{row.name}(tone)" for row in HUES]
    lines += ["        }", "    }"]
    for row in HUES:
        lines += [
            "",
            f"    /// Returns {row.name} at a tone.",
            "    ///",
            "    /// - Parameter tone: The tone to read.",
            "    /// - Returns: The color at that tone.",
            f"    private static func {row.name}(_ tone: Tone) -> Color.Resolved {{"
            "  // swiftlint:disable:this cyclomatic_complexity",
            "        switch tone {",
        ]
        lines += [f"        case .t{t}: {literal(rgb)}" for t, _, rgb in ramps[row.name]]
        lines += ["        }", "    }"]
    lines += ["}", "// swiftlint:enable no_magic_numbers"]
    return lines


def check_formatting(name, lines):
    """Fail when a line is 120 characters or longer or ends in a space."""
    for number, line in enumerate(lines, 1):
        if len(line) >= 120 or line != line.rstrip():
            fail(f"{name} line {number} breaks the formatting rules: {line!r}")


LITERAL_PATTERN = re.compile(
    r"case \.t(\d+): Color\.Resolved\(colorSpace: \.displayP3, "
    r"red: ([-0-9.]+), green: ([-0-9.]+), blue: ([-0-9.]+)\)"
)


def p3_oklab(rgb):
    """Returns (L, a, b) of gamma-encoded Display P3 components."""
    linear_p3 = [decode(c) for c in rgb]
    return linear_srgb_to_oklab(mat_vec(P3_TO_SRGB, linear_p3))


def p3_oklch(rgb):
    """Returns (L, C, hue in degrees) of gamma-encoded Display P3 components."""
    lab = p3_oklab(rgb)
    return lab[0], math.hypot(lab[1], lab[2]), math.degrees(math.atan2(lab[2], lab[1])) % 360


HUE_CHECK_CHROMA = 0.05  # Below this chroma a hue angle is too unstable to check.
HUE_TOLERANCE = 1.0  # Degrees of hue a rounded literal may drift from its row's angle.


def self_check(name, text, expected_count):
    """Parse every literal in the Swift text back; compare L x 100 with its tone and its hue with its row."""
    count = 0
    for index, match in enumerate(LITERAL_PATTERN.finditer(text)):
        rgb = [float(match.group(g)) for g in (2, 3, 4)]
        tone = int(match.group(1))
        lightness, chroma, hue = p3_oklch(rgb)
        measured = lightness * 100
        if abs(measured - tone) > 0.5:
            fail(f"self-check: {name} literal {index} at t{tone} has L x 100 = {measured:.3f}")
        row = HUES[index // len(TONES)]
        drift = abs((hue - row.angle_at(tone) + 180) % 360 - 180)
        if chroma >= HUE_CHECK_CHROMA and drift > HUE_TOLERANCE:
            fail(f"self-check: {name} {row.name} t{tone} has hue {hue:.1f}, expected {row.angle_at(tone):.1f}")
        count += 1
    if count != expected_count:
        fail(f"self-check: {name} held {count} values, expected {expected_count}")
    print(f"self-check: {count} values ok")


def progress(row, tones):
    """Print one progress line for a finished hue."""
    peak_tone, peak_chroma, _ = max(tones, key=lambda item: item[1])
    hue = f"hue {row.angle:.1f}" if row.turn_to is None else f"hue {row.angle:.1f} turning to {row.turn_to:.1f}"
    print(f"{row.name}: {len(tones)} tones, peak chroma {peak_chroma:.3f} at t{peak_tone} ({hue})")


# Each family is a name and the Hue it draws from.
FAMILIES = [
    ("success", "green"),
    ("warning", "yellow"),
    ("error", "red"),
    ("info", "blue"),
    ("neutral", "neutral"),
    ("blue", "blue"),
    ("teal", "teal"),
    ("violet", "violet"),
    ("raspberry", "raspberry"),
    ("sponsor", "mauve"),
]

# The appearances of one color set, in the order Xcode writes them, each with its JSON appearance entries.
APPEARANCES = [
    ("light", []),
    ("dark", [{"appearance": "luminosity", "value": "dark"}]),
    ("light high contrast", [{"appearance": "contrast", "value": "high"}]),
    (
        "dark high contrast",
        [{"appearance": "luminosity", "value": "dark"}, {"appearance": "contrast", "value": "high"}],
    ),
]

# One tone per appearance, in APPEARANCES order: light, dark, light high contrast, dark high contrast.
ROLE_TONES = {
    "text": (45, 75, 40, 80),
    "solid": (50, 60, 40, 65),
    "onSolid": (95, 5, 95, 5),
    "subtle": (95, 20, 95, 15),
}

# Warning is a pale yellow fill with dark text, as Carbon's and Atlassian's. The light Increase
# Contrast fill stays t85: a darker text on it raises the ratio, and a t80 fill lowered it.
# build_catalog fails on a key that names no family or role.
FAMILY_ROLE_TONES = {
    ("warning", "text"): (50, 75, 45, 80),
    ("warning", "solid"): (85, 80, 85, 85),
    ("warning", "onSolid"): (10, 5, 5, 5),
}


def tones_for(family, role):
    """Returns the four tones of a family's role, one per appearance."""
    return FAMILY_ROLE_TONES.get((family, role), ROLE_TONES[role])


# Two families that share a role on one screen must read as two colours. Distance is the OKLab
# distance times 100 (about 2 is a just-noticeable difference). Text: the rejected warning and
# error text pair measured under 8 in every light appearance, and the lowest shipped AA text pair
# (GOV.UK's tags) measured 9.4, so 10 sits above both. Fills: Carbon's and Atlassian's warning
# and error fills sit at 34, and our closest status fill pair at 27.
SEPARATION_FLOORS = {"text": 10.0, "solid": 20.0}
# The families checked on text, and reported on subtle. Sponsor is in: its text shares screens
# with status text.
SEPARATED_TEXT = ("success", "warning", "error", "info", "sponsor")
# The families checked on solid. A sponsor fill never sits beside a status fill.
SEPARATED_FILLS = ("success", "warning", "error", "info")


CATALOG_NAME = "Colors.xcassets"
CATALOG_INFO = {"author": "xcode", "version": 1}


def component_text(value):
    """Returns a color component as Xcode writes it: a decimal string with four places."""
    return f"{value:.{DECIMALS}f}"


def colorset_entry(rgb, appearances):
    """Returns one entry of a color set: Display P3 components under the given appearances."""
    entry = {
        "color": {
            "color-space": "display-p3",
            "components": {
                "alpha": "1.000",
                "blue": component_text(rgb[2]),
                "green": component_text(rgb[1]),
                "red": component_text(rgb[0]),
            },
        },
        "idiom": "universal",
    }
    if appearances:
        entry["appearances"] = appearances
    return entry


def json_text(value):
    """Returns JSON as Xcode writes it: two-space indent, a space before each colon, a final newline."""
    return json.dumps(value, indent=2, separators=(",", " : "), sort_keys=True) + "\n"


def colorset_text(family, role, ramps, hue_name):
    """Returns the Contents.json text of one color set."""
    by_tone = {tone: rgb for tone, _, rgb in ramps[hue_name]}
    entries = [
        colorset_entry(by_tone[tone], appearances)
        for tone, (_, appearances) in zip(tones_for(family, role), APPEARANCES)
    ]
    return json_text({"colors": entries, "info": CATALOG_INFO})


def build_catalog(ramps):
    """Returns the catalog as a dict of relative path -> text, and prints one line per family."""
    files = {"Contents.json": json_text({"info": CATALOG_INFO})}
    hue_names = {row.name for row in HUES}
    family_names = {family for family, _ in FAMILIES}
    for family, role in FAMILY_ROLE_TONES:
        if family not in family_names or role not in ROLE_TONES:
            fail(f"FAMILY_ROLE_TONES names an unknown family or role: {family}, {role}")
    for family, hue_name in FAMILIES:
        if hue_name not in hue_names:
            fail(f"family {family} names an unknown hue: {hue_name}")
        for role in ROLE_TONES:
            for tone in tones_for(family, role):
                if tone not in TONES:
                    fail(f"family {family} role {role} names a tone that is not in the ramp: {tone}")
            files[f"{family}-{role}.colorset/Contents.json"] = colorset_text(family, role, ramps, hue_name)
        count = len(ROLE_TONES) * len(APPEARANCES)
        print(f"{family} ({hue_name}): {len(ROLE_TONES)} roles, {count} values")
    return files


def check_catalog(files, ramps):
    """Parse every written component back and compare it with the tone literal it came from."""
    hue_of = dict(FAMILIES)
    count = 0
    for relative, text in files.items():
        if relative == "Contents.json":
            continue
        family, role = relative.split(".colorset/")[0].split("-")
        by_tone = {tone: rgb for tone, _, rgb in ramps[hue_of[family]]}
        entries = json.loads(text)["colors"]
        if len(entries) != len(APPEARANCES):
            fail(f"self-check: {relative} held {len(entries)} entries, expected {len(APPEARANCES)}")
        for entry, tone, (label, appearances) in zip(entries, tones_for(family, role), APPEARANCES):
            if entry.get("appearances", []) != appearances:
                fail(f"self-check: {relative} {label} has the wrong appearances")
            color = entry["color"]
            if color["color-space"] != "display-p3" or color["components"]["alpha"] != "1.000":
                fail(f"self-check: {relative} {label} is not opaque Display P3")
            parsed = [float(color["components"][key]) for key in ("red", "green", "blue")]
            expected = [float(component_text(c)) for c in by_tone[tone]]
            if parsed != expected:
                fail(f"self-check: {relative} {label} read {parsed}, expected t{tone} {expected}")
            count += 1
    expected_count = len(FAMILIES) * len(ROLE_TONES) * len(APPEARANCES)
    if count != expected_count:
        fail(f"self-check: catalog held {count} values, expected {expected_count}")
    print(f"self-check: {count} catalog values ok")


def check_separation(ramps):
    """Fail when two families that share a role sit closer than that role's floor in any appearance."""
    hue_of = dict(FAMILIES)

    def colour(family, role, index):
        tone = tones_for(family, role)[index]
        return next(rgb for ramp_tone, _, rgb in ramps[hue_of[family]] if ramp_tone == tone)

    # Subtle is reported only: pale tints sit at 2 to 10 apart and carry no state alone.
    for role, families in (("text", SEPARATED_TEXT), ("solid", SEPARATED_FILLS), ("subtle", SEPARATED_TEXT)):
        closest = None
        for first, second in itertools.combinations(families, 2):
            for index in range(len(APPEARANCES)):
                lab_first = p3_oklab(colour(first, role, index))
                lab_second = p3_oklab(colour(second, role, index))
                distance = 100 * math.sqrt(sum((a - b) ** 2 for a, b in zip(lab_first, lab_second)))
                if closest is None or distance < closest[0]:
                    closest = (distance, first, second, APPEARANCES[index][0])
        distance, first, second, label = closest
        print(f"separation {role}: closest {first} and {second} at {distance:.1f} ({label})")
        floor = SEPARATION_FLOORS.get(role)
        if floor is not None and distance < floor:
            fail(f"separation: {role} of {first} and {second} is {distance:.1f} apart in {label}, floor {floor}")


def check_stray_files(catalog):
    """Fail when the catalog folder holds anything the tables do not produce, before it is deleted."""
    if not catalog.exists():
        return
    allowed = {"Contents.json"} | {
        f"{family}-{role}.colorset" for family, _ in FAMILIES for role in ROLE_TONES
    }
    for child in sorted(catalog.iterdir()):
        if child.name not in allowed:
            fail(f"{catalog} holds a file the generator did not write: {child.name}. Remove it or move it.")
        if child.is_dir() and [item.name for item in child.iterdir()] != ["Contents.json"]:
            fail(f"{child} holds more than Contents.json")


def write_catalog(catalog, files):
    """Delete the catalog folder and write every file again. run() has checked it for stray files."""
    if catalog.exists():
        shutil.rmtree(catalog)
    for relative, text in files.items():
        path = catalog / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {catalog} ({len(files) - 1} color sets)")


def run(swift_directory, resources_directory):
    """Build every ramp and the catalog, check both, then write them."""
    swift_directory.mkdir(parents=True, exist_ok=True)
    ramps = {}
    for row in HUES:
        ramps[row.name] = ramp(row)
        progress(row, ramps[row.name])
    path = swift_directory / "Hue+Tones.swift"
    lines = hue_file(ramps)
    check_formatting(path.name, lines)
    text = "\n".join(lines) + "\n"
    self_check(path.name, text, len(HUES) * len(TONES))
    files = build_catalog(ramps)
    check_catalog(files, ramps)
    check_separation(ramps)
    check_stray_files(resources_directory / CATALOG_NAME)
    path.write_text(text, encoding="utf-8")
    print("hue cases: " + ", ".join(row.name for row in HUES))
    print(f"wrote {path}")
    write_catalog(resources_directory / CATALOG_NAME, files)


def main():
    """Read the arguments and run, logging any unexpected error."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--output-root", type=Path, help="write Hue+Tones.swift and Colors.xcassets straight into this directory"
    )
    arguments = parser.parse_args()
    sources = DEFAULT_ROOT / "Packages/DesignSystem/UIDesign/Sources/UIDesign"
    swift_directory, resources_directory = sources / "Tokens/Colors/Hue", sources / "Resources"
    if arguments.output_root:
        swift_directory = resources_directory = arguments.output_root
    try:
        run(swift_directory, resources_directory)
    except SystemExit:
        raise
    except Exception as error:  # noqa: BLE001
        fail(f"unexpected {type(error).__name__}: {error}")


if __name__ == "__main__":
    main()
